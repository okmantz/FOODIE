#!/usr/bin/env node
/**
 * Generates js/data/recipes-more.js — additional original recipes for FOODIE.
 *
 *   node tools/generate-recipes.mjs          # (re)write js/data/recipes-more.js
 *   node tools/generate-recipes.mjs --report # print per-family counts and rejects
 *
 * Every recipe is assembled from curated, cooking-realistic building blocks
 * (proteins with correct cook times and food-safety temperatures, matching
 * flavor kits, seasonal vegetables, sensible starches). Each result is then
 * checked against the ingredient database (known ingredients, sane per-serving
 * calories, protein, cost, step count) and anything that fails is dropped.
 * Nutrition, allergens, diet flags and cost are derived at runtime from the
 * ingredient database, exactly like the hand-written recipes.
 */
import fs from 'node:fs';
import { BUILTIN_RECIPES } from '../js/data/recipes.js';
import { slug, qc } from './lib.mjs';
import * as dinner from './templates-dinner.mjs';
import * as dinner2 from './templates-dinner2.mjs';
import * as light from './templates-light.mjs';

const report = process.argv.includes('--report');
const FAMILIES = [
  ['sheet-pan', dinner.sheetPan, 110], ['skillet', dinner.skillet, 120], ['stir-fry', dinner.stirFry, 70], ['curries', dinner.curries, 90],
  ['pasta', dinner2.pasta, 70], ['handhelds', dinner2.handhelds, 80], ['bakes', dinner2.bakes, 90], ['soups', dinner2.soups, 70],
  ['bowls', light.bowls, 100], ['salads', light.salads, 50], ['sandwiches', light.sandwiches, 55], ['breakfast', light.breakfasts, 115],
  ['snacks', light.snacks, 60], ['desserts', light.desserts, 70], ['smoothies', light.smoothies, 60],
];

const usedIds = new Set(BUILTIN_RECIPES.map((r) => r.id));
const usedNames = new Set(BUILTIN_RECIPES.map((r) => r.n.toLowerCase()));
const out = []; const stats = [];

for (const [name, fn, cap] of FAMILIES) {
  let cands = fn(); const total = cands.length; const rejects = [];
  // balance: round-robin across protein/group so one protein doesn't dominate the cap
  const byGrp = new Map(); for (const c of cands) { const g = c.grp || 'x'; if (!byGrp.has(g)) byGrp.set(g, []); byGrp.get(g).push(c); }
  const queues = [...byGrp.values()]; const ordered = [];
  for (let i = 0; ordered.length < cands.length; i++) { let any = false; for (const q of queues) if (q[i]) { ordered.push(q[i]); any = true; } if (!any) break; }
  let kept = 0;
  for (const c of ordered) {
    if (kept >= cap) break;
    const rec = c.rec; const items = rec ? rec.items() : c.i; const servings = rec ? rec.s : c.s;
    const r = { id: slug(c.n), n: c.n, c: c.c, t: c.t, e: c.e, p: c.p, k: c.k, s: servings, i: items, st: c.st };
    if (c.sl) r.sl = c.sl; if (c.se) r.se = c.se; if (c.tip) r.tip = c.tip; r.proteinMeal = c.proteinMeal;
    if (usedIds.has(r.id) || usedNames.has(r.n.toLowerCase())) continue;
    const q = qc(r);
    if (!q.ok) { rejects.push(`${r.n}: ${q.why.join(', ')}`); continue; }
    delete r.proteinMeal; usedIds.add(r.id); usedNames.add(r.n.toLowerCase()); out.push(r); kept++;
  }
  stats.push([name, total, kept, rejects]);
}

const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const fmt = (r) => {
  const parts = [`id: ${q(r.id)}`, `n: ${q(r.n)}`, `c: ${q(r.c)}`, `t: ${q(r.t)}`, `e: ${q(r.e)}`, `p: ${r.p}`, `k: ${r.k}`, `s: ${r.s}`,
    `i: [${r.i.map(([id, n]) => `[${q(id)}, ${n}]`).join(', ')}]`, `st: [${r.st.map(q).join(', ')}]`];
  if (r.sl) parts.push(`sl: [${r.sl.map(q).join(', ')}]`);
  if (r.se) parts.push(`se: [${r.se.map(q).join(', ')}]`);
  if (r.tip) parts.push(`tip: ${q(r.tip)}`);
  return `  { ${parts.join(', ')} },`;
};
const header = `/**
 * Additional built-in recipes (original, generated by tools/generate-recipes.mjs).
 * Same compact format as recipes.js; nutrition, allergens, diet flags and cost
 * are derived from the ingredient database at runtime. Re-run the generator
 * instead of editing this file by hand.
 */
export const MORE_RECIPES = [
`;
fs.writeFileSync(new URL('../js/data/recipes-more.js', import.meta.url), header + out.map(fmt).join('\n') + '\n];\n');
console.log(`wrote ${out.length} recipes (total with built-ins: ${out.length + BUILTIN_RECIPES.length})`);
for (const [name, total, kept, rej] of stats) { console.log(`${name.padEnd(12)} candidates ${String(total).padStart(4)}  kept ${String(kept).padStart(4)}  rejected-by-QC ${rej.length}`); if (report) rej.slice(0, 6).forEach((x) => console.log('    ✗', x)); }
